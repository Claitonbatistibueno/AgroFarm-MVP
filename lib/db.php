<?php
/* =========================================================
   lib/db.php — database access layer on top of PDO (PostgreSQL / Supabase)

   The pages were written against the mysqli API ($conn->prepare,
   bind_param, get_result, fetch_assoc ...). These classes keep that
   same small API but run everything through PDO, so the database can
   be PostgreSQL (Supabase) without rewriting every page.

   Supported:  FarmDb::prepare/query/begin_transaction/commit/rollback,
               ->insert_id, ->error
               FarmStmt::bind_param/execute/get_result/store_result/close,
               ->num_rows, ->affected_rows, ->insert_id, ->error
               FarmResult::fetch_assoc/fetch_row/fetch_all/data_seek/free,
               ->num_rows, foreach
   ========================================================= */

if (!defined('FARM_ASSOC')) { define('FARM_ASSOC', 1); }

class FarmDb
{
    public PDO $pdo;
    public int $insert_id = 0;
    public string $error = '';

    public function __construct(PDO $pdo) { $this->pdo = $pdo; }

    public function prepare(string $sql): FarmStmt
    {
        return new FarmStmt($this, $this->pdo->prepare($sql), $sql);
    }

    /** Runs a statement without parameters. SELECT returns a FarmResult, anything else true. */
    public function query(string $sql): FarmResult|bool
    {
        $stmt = $this->pdo->query($sql);
        if ($stmt->columnCount() > 0) {
            return new FarmResult($stmt->fetchAll(PDO::FETCH_ASSOC));
        }
        $this->refreshInsertId($sql);
        return true;
    }

    public function begin_transaction(): bool { return $this->pdo->beginTransaction(); }
    public function commit(): bool            { return $this->pdo->inTransaction() ? $this->pdo->commit() : true; }
    public function rollback(): bool          { return $this->pdo->inTransaction() ? $this->pdo->rollBack() : true; }
    public function set_charset(string $c): bool { return true; }
    public function close(): bool             { return true; }

    /** After an INSERT, read the id generated by the table's sequence. */
    public function refreshInsertId(string $sql): int
    {
        if (!preg_match('/^\s*insert\b/i', $sql)) { return $this->insert_id; }
        try {
            $this->insert_id = (int) $this->pdo->query('SELECT lastval()')->fetchColumn();
        } catch (PDOException $e) {
            // table without a sequence: keep the previous value
        }
        return $this->insert_id;
    }
}

class FarmStmt
{
    public int $num_rows = 0;
    public int $affected_rows = 0;
    public int $insert_id = 0;
    public string $error = '';

    private string $types = '';
    /** @var array<int, mixed> references to the caller's variables */
    private array $vars = [];
    private ?array $rows = null;

    public function __construct(private FarmDb $db, private PDOStatement $stmt, private string $sql) {}

    /** Same contract as mysqli: variables are read when execute() runs. */
    public function bind_param(string $types, mixed &...$vars): bool
    {
        $this->types = $types;
        $this->vars = [];
        foreach ($vars as $i => &$v) { $this->vars[$i] = &$v; }
        return true;
    }

    /** execute() uses bind_param() values; execute([...]) works like PDO. */
    public function execute(?array $params = null): bool
    {
        if ($params === null) {
            $params = [];
            foreach ($this->vars as $i => $v) {
                $params[] = self::cast($this->types[$i] ?? 's', $v);
            }
        }
        foreach (array_values($params) as $i => $v) {
            $type = match (true) {
                $v === null    => PDO::PARAM_NULL,
                is_int($v)     => PDO::PARAM_INT,
                is_bool($v)    => PDO::PARAM_BOOL,
                default        => PDO::PARAM_STR,
            };
            $this->stmt->bindValue($i + 1, is_float($v) ? (string) $v : $v, $type);
        }

        $this->stmt->execute();
        $this->affected_rows = $this->stmt->rowCount();
        $this->rows = null;
        if ($this->stmt->columnCount() > 0) {
            $this->rows = $this->stmt->fetchAll(PDO::FETCH_ASSOC);
            $this->num_rows = count($this->rows);
        } else {
            $this->insert_id = $this->db->refreshInsertId($this->sql);
        }
        return true;
    }

    public function get_result(): FarmResult { return new FarmResult($this->rows ?? []); }
    public function store_result(): bool     { return true; }
    public function close(): bool            { $this->stmt->closeCursor(); return true; }

    /** mysqli type letters: i = integer, d = double, s = string, b = blob. */
    private static function cast(string $type, mixed $v): mixed
    {
        if ($v === null) { return null; }
        return match ($type) {
            'i'     => (int) $v,
            'd'     => (float) $v,
            default => (string) $v,
        };
    }
}

class FarmResult implements IteratorAggregate, Countable
{
    public int $num_rows;
    private int $pos = 0;

    public function __construct(private array $rows) { $this->num_rows = count($rows); }

    public function fetch_assoc(): ?array
    {
        return $this->rows[$this->pos++] ?? null;
    }

    public function fetch_row(): ?array
    {
        $row = $this->fetch_assoc();
        return $row === null ? null : array_values($row);
    }

    public function fetch_all(int $mode = FARM_ASSOC): array
    {
        return $this->rows;
    }

    public function data_seek(int $offset): bool
    {
        $this->pos = max(0, $offset);
        return true;
    }

    public function free(): void {}

    /** foreach ($result as $row) works like it does with mysqli_result. */
    public function getIterator(): ArrayIterator { return new ArrayIterator($this->rows); }
    public function count(): int { return $this->num_rows; }
}
